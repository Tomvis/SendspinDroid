// ── PROXY-mode auth (not part of the Sendspin spec; specific to the
//    authenticated reverse-proxy transport used on this fork).
@JsonClass(generateAdapter = true)
internal data class WireProxyAuthMessage(
    @Json(name = "type") val type: String = "auth",
    @Json(name = "token") val token: String,
    @Json(name = "client_id") val clientId: String,
)

/**
 * Server response on the proxy auth channel. Successful auth doesn't return
 * anything specific (the server sends a `server/hello` once the connection
 * is accepted); failure messages look like `{"type":"auth_failed","message":"..."}`
 * or `{"type":"error","message":"..."}`.
 */
@JsonClass(generateAdapter = true)
internal data class WireProxyAuthResponse(
    @Json(name = "type") val type: String? = null,
    @Json(name = "message") val message: String? = null,
)

