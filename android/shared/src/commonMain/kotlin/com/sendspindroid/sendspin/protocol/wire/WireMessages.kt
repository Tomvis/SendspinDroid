@JsonClass(generateAdapter = true)
internal data class WireMetadata(
    @Json(name = "timestamp") val timestamp: Long? = null,
    @Json(name = "title") val title: JsonOptional<String> = JsonOptional.Absent,
    @Json(name = "artist") val artist: JsonOptional<String> = JsonOptional.Absent,
    @Json(name = "album_artist") val albumArtist: JsonOptional<String> = JsonOptional.Absent,
    @Json(name = "album") val album: JsonOptional<String> = JsonOptional.Absent,
    @Json(name = "artwork_url") val artworkUrl: JsonOptional<String> = JsonOptional.Absent,
    @Json(name = "year") val year: JsonOptional<Int> = JsonOptional.Absent,
    @Json(name = "album_track") val albumTrack: JsonOptional<Int> = JsonOptional.Absent,
    @Json(name = "track") val legacyTrack: JsonOptional<Int> = JsonOptional.Absent,
    @Json(name = "queue_track") val queueTrack: JsonOptional<Int> = JsonOptional.Absent,
    @Json(name = "total_tracks") val totalTracks: JsonOptional<Int> = JsonOptional.Absent,
    @Json(name = "progress") val progress: JsonOptional<WireProgress> = JsonOptional.Absent,
    // Legacy flat progress (pre-nested-progress servers)
    @Json(name = "position_ms") val legacyPositionMs: JsonOptional<Long> = JsonOptional.Absent,
    @Json(name = "duration_ms") val legacyDurationMs: JsonOptional<Long> = JsonOptional.Absent,
    @Json(name = "playback_speed") val legacyPlaybackSpeed: JsonOptional<Int> = JsonOptional.Absent,
    // Legacy controller fields (pre-controller-object servers)
    @Json(name = "repeat") val legacyRepeat: JsonOptional<String> = JsonOptional.Absent,
    @Json(name = "shuffle") val legacyShuffle: JsonOptional<Boolean> = JsonOptional.Absent,
)

@JsonClass(generateAdapter = true)
