package com.sendspindroid.sendspin.protocol.wire

import com.sendspindroid.sendspin.protocol.JsonOptional
import com.squareup.moshi.Json
import com.squareup.moshi.JsonClass

/**
 * Wire-level representations of every Sendspin JSON message we send or receive.
 *
 * These types map 1:1 to the JSON shapes on the wire. Higher-level domain
 * types in `SendSpinProtocol.kt` (TrackMetadata, ControllerState, ColorState,
 * etc.) are derived from these by the message parser, which is where merge-with-
 * previous and legacy-fallback logic lives.
 *
 * Fields that need to distinguish JSON-absent from JSON-null use
 * [JsonOptional]; fields where absent ≡ null use a nullable type with a
 * default of null.
 *
 * All adapters are generated by KSP via moshi-kotlin-codegen; nothing here
 * uses runtime reflection on the audio hot path.
 */

// ── Incoming ──────────────────────────────────────────────────────────────

// Incoming wire types: scalar fields are nullable with `= null` defaults so
// that `present-but-null` JSON does not throw `JsonDataException` from the
// KSP-generated adapter. Defaults are applied at the domain-mapping step.
@JsonClass(generateAdapter = true)
internal data class WireServerHelloPayload(
    @Json(name = "name") val name: String? = null,
    @Json(name = "server_id") val serverId: String? = null,
    @Json(name = "version") val version: Int? = null,
    @Json(name = "active_roles") val activeRoles: List<String>? = null,
    @Json(name = "connection_reason") val connectionReason: String? = null,
)

@JsonClass(generateAdapter = true)
internal data class WireServerTimePayload(
    @Json(name = "client_transmitted") val clientTransmitted: Long? = null,
    @Json(name = "server_received") val serverReceived: Long? = null,
    @Json(name = "server_transmitted") val serverTransmitted: Long? = null,
)

@JsonClass(generateAdapter = true)
internal data class WireServerStatePayload(
    @Json(name = "metadata") val metadata: WireMetadata? = null,
    @Json(name = "state") val state: String? = null,
    @Json(name = "controller") val controller: WireController? = null,
    @Json(name = "color") val color: WireColor? = null,
